"""Candidate test-case generation.

Tests are represented as reviewable :class:`TestCaseSpec` rows (call expression
+ expected value or expected exception). The LLM proposes them; the user can
edit them in the UI; :func:`render_pytest` turns them into a pytest file.

LLM-generated tests are *candidates*: they encode the model's understanding of
the intended behaviour and may themselves be wrong. Independent benchmark tests
(``datasets/benchmark.json``) are kept separate and are never generated by the LLM.
"""

from __future__ import annotations

import ast
import keyword
import re
from typing import Optional

from core.llm_engine import LLMClient, LLMError
from core.syntax_checker import FunctionInfo, analyze_syntax
from utils.logger import get_logger
from utils.prompts import SYSTEM_PROMPT, build_test_prompt
from utils.validators import AITestResponse, TestCaseSpec

logger = get_logger("test_generator")

FORBIDDEN_NAMES = {"eval", "exec", "open", "__import__", "compile", "input", "globals", "locals", "vars",
                   "getattr", "setattr", "delattr", "breakpoint", "exit", "quit"}

PYTEST_HEADER = '''"""Tests generated by CodeMind AI. Review them before trusting the results."""
import math

import pytest

from solution import *  # noqa: F401,F403  (the code under test is saved as solution.py)


def _matches(actual, expected):
    """Equality that tolerates float rounding inside numbers, lists and tuples."""
    if isinstance(expected, float) or isinstance(actual, float):
        try:
            return math.isclose(actual, expected, rel_tol=1e-6, abs_tol=1e-9)
        except TypeError:
            return False
    if isinstance(expected, (list, tuple)) and isinstance(actual, (list, tuple)):
        return type(actual) is type(expected) and len(actual) == len(expected) and all(
            _matches(a, e) for a, e in zip(actual, expected))
    return actual == expected
'''


class UnsafeTestError(ValueError):
    """Raised when a test expression is not a plain, safe Python expression."""


def check_expression(expression: str) -> None:
    """Validate that ``expression`` is a single, side-effect-light expression.

    This is a usability/safety filter; the real protection is the sandbox.
    """
    try:
        tree = ast.parse(expression.strip(), mode="eval")
    except SyntaxError as exc:
        raise UnsafeTestError(f"Not a valid Python expression: {expression!r}") from exc
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and node.id in FORBIDDEN_NAMES:
            raise UnsafeTestError(f"Use of '{node.id}' is not allowed in tests.")
        if isinstance(node, ast.Attribute) and node.attr.startswith("__"):
            raise UnsafeTestError("Dunder attribute access is not allowed in tests.")
        if isinstance(node, (ast.Lambda, ast.NamedExpr, ast.Await, ast.Yield, ast.YieldFrom)):
            raise UnsafeTestError("Lambdas, walrus, await and yield are not allowed in test expressions.")


def _safe_identifier(name: str, index: int) -> str:
    ident = re.sub(r"\W+", "_", name.strip().lower()).strip("_") or f"case_{index}"
    if not ident.startswith("test_"):
        ident = f"test_{ident}"
    if keyword.iskeyword(ident) or not ident.isidentifier():
        ident = f"test_case_{index}"
    return ident


def _valid_exception(name: str) -> Optional[str]:
    name = name.strip()
    if not name:
        return None
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
        raise UnsafeTestError(f"Invalid exception name: {name!r}")
    return name


def render_pytest(specs: list[TestCaseSpec]) -> tuple[str, list[str]]:
    """Render test specs as a pytest module.

    Returns:
        (source_code, warnings) – specs that fail validation are skipped and
        reported in ``warnings``.
    """
    lines = [PYTEST_HEADER]
    warnings: list[str] = []
    used: set[str] = set()
    for index, spec in enumerate(specs, start=1):
        try:
            check_expression(spec.call)
            exception = _valid_exception(spec.expects_exception)
            if not exception:
                if not spec.expected.strip():
                    raise UnsafeTestError("Expected value is empty.")
                check_expression(spec.expected)
        except UnsafeTestError as exc:
            warnings.append(f"Skipped '{spec.name}': {exc}")
            continue
        name = _safe_identifier(spec.name, index)
        while name in used:
            name = f"{name}_{index}"
        used.add(name)
        doc = (spec.description or spec.category).replace('"""', "'").replace("\\", "/")[:150]
        lines.append("")
        lines.append("")
        lines.append(f"def {name}():")
        lines.append(f'    """[{spec.category}] {doc}"""')
        if exception:
            lines.append(f"    with pytest.raises({exception}):")
            lines.append(f"        {spec.call.strip()}")
        else:
            lines.append(f"    actual = {spec.call.strip()}")
            lines.append(f"    expected = {spec.expected.strip()}")
            lines.append("    assert _matches(actual, expected), f'expected {expected!r}, got {actual!r}'")
    return "\n".join(lines) + "\n", warnings


def testable_functions(code: str) -> list[FunctionInfo]:
    """Top-level, public functions that are good test targets."""
    report = analyze_syntax(code)
    return [f for f in report.functions if not f.is_method and not f.name.startswith("_")]


def generate_tests_with_llm(llm: LLMClient, code: str, expected_behavior: str = "",
                            count: int = 8) -> tuple[list[TestCaseSpec], str]:
    """Ask the LLM for candidate test cases.

    Returns:
        (specs, error_message). On failure specs is empty and the message explains why.
    """
    functions = testable_functions(code)
    if not functions:
        return [], "No top-level functions found to test. Wrap your logic in a function first."
    prompt = build_test_prompt(code, [f.name for f in functions], expected_behavior, count)
    try:
        response = llm.generate_json(prompt, AITestResponse, system=SYSTEM_PROMPT)
    except LLMError as exc:
        logger.warning("test generation failed", extra={"error": str(exc)})
        return [], str(exc)
    valid: list[TestCaseSpec] = []
    for spec in response.tests:
        try:
            check_expression(spec.call)
            valid.append(spec)
        except UnsafeTestError as exc:
            logger.info("dropped unsafe generated test", extra={"reason": str(exc)})
    return valid, "" if valid else "The model did not return any usable test cases."


def template_specs(code: str) -> list[TestCaseSpec]:
    """Editable starter rows (one per function) for when no LLM is available.

    The expected values are intentionally left for the user to fill in, and
    such rows are skipped by :func:`render_pytest` until they are completed.
    """
    specs = []
    for func in testable_functions(code):
        args = ", ".join("..." for _ in func.args) if func.args else ""
        specs.append(TestCaseSpec(name=f"test_{func.name}_normal", category="normal", call=f"{func.name}({args})",
                                  expected="", description=f"Fill in arguments and the expected result of "
                                                           f"{func.name}"))
    return specs
