"""Code Optimizer page: measured metrics, rule-based and AI suggestions."""

from __future__ import annotations

import plotly.graph_objects as go
import streamlit as st

from core.code_comparator import compare_code, render_side_by_side_html
from core.optimizer import OptimizationReport, analyze_optimizations
from views.components import (code_editor, current_settings, get_llm, metric_card, metric_row, page_header,
                              plotly_layout)

CATEGORY_ICONS = {"performance": "⚡", "readability": "📖", "redundancy": "♻️", "complexity": "🧩",
                  "standards": "📏", "memory": "💾"}


def render() -> None:
    page_header("Code Optimizer", "Measured metrics, rule-based improvements and AI estimates — clearly separated.",
                "⚡")
    settings = current_settings()
    with st.expander("Code (shared with the debugger)", expanded=not st.session_state.code.strip()):
        code_editor("optimizer", height=300)

    col1, col2 = st.columns([3, 1])
    with col1:
        use_ai = st.toggle("Include AI suggestions (Ollama)", value=True)
    with col2:
        run = st.button("Analyse optimisations", type="primary", icon=":material/speed:", width="stretch")
    if run:
        if not st.session_state.code.strip():
            st.warning("Please enter some code first.")
        else:
            llm = get_llm(settings) if use_ai else None
            if use_ai and llm is None:
                st.info("Ollama is not available; showing measured and rule-based results only.")
            with st.spinner("Analysing…"):
                st.session_state.opt_report = analyze_optimizations(st.session_state.code, llm)

    report: OptimizationReport | None = st.session_state.opt_report
    if report is None:
        return
    m = report.metrics
    st.markdown('<div class="cm-section-title">📐 Measured metrics (Radon)</div>', unsafe_allow_html=True)
    if not m.available:
        st.warning(m.error)
    metric_row([
        metric_card("Lines of code", m.loc, f"{m.sloc} source · {m.comments} comment", "purple"),
        metric_card("Avg. complexity", m.average_complexity, f"max {m.max_complexity}", "blue"),
        metric_card("Maintainability", m.maintainability_index, "0–100, higher is better", "green"),
        metric_card("Halstead volume", m.halstead_volume, f"effort {m.halstead_effort:.0f}", "default"),
        metric_card("Heuristic time", report.heuristic_time_complexity, "estimate from loop depth", "yellow"),
        metric_card("Heuristic space", report.heuristic_space_complexity, "estimate, auxiliary memory", "yellow"),
    ])
    st.caption(f"Heuristic reasoning (not measured). Time: {report.heuristic_reason} "
               f"Space: {report.heuristic_space_reason}")
    if m.functions:
        fig = go.Figure(go.Bar(x=[f.name for f in m.functions], y=[f.complexity for f in m.functions],
                               marker_color=["#FF5C7A" if f.complexity > 10 else "#7C6CFF" for f in m.functions]))
        fig.add_hline(y=10, line_dash="dot", line_color="#F5C451", annotation_text="threshold 10")
        fig.update_layout(title="Cyclomatic complexity per function", yaxis_title="complexity")
        st.plotly_chart(plotly_layout(fig, 300), width="stretch")

    left, right = st.columns(2)
    with left:
        st.markdown('<div class="cm-section-title">🔎 Rule-based suggestions</div>', unsafe_allow_html=True)
        st.caption("Patterns confirmed in the AST; benefits are general guidelines.")
        if not report.suggestions:
            st.success("No rule-based optimisation opportunities found.")
        for s in report.suggestions:
            icon = CATEGORY_ICONS.get(s.category, "•")
            source = "measured" if s.source == "measured" else "rule"
            with st.container(border=True):
                st.markdown(f"{icon} **{s.title}** · line {s.line or '–'} · `{s.category}` · _{source}_")
                st.caption(s.detail)
    with right:
        st.markdown('<div class="cm-section-title">🤖 AI suggestions (estimates)</div>', unsafe_allow_html=True)
        st.caption("Generated by the LLM; verify before applying.")
        if report.ai_error:
            st.warning(f"AI suggestions unavailable: {report.ai_error}")
        elif report.heuristic_time_complexity == "n/a":
            st.info("The code does not parse yet. Fix the syntax error (see the AI Code Debugger), then analyse again.")
        elif not (report.ai_suggestions or report.ai_explanation):
            st.info("AI suggestions were not requested or Ollama is offline.")
        else:
            st.markdown(f"**Estimated time complexity:** `{report.ai_time_complexity}` · "
                        f"**space:** `{report.ai_space_complexity}`")
            for item in report.ai_suggestions:
                st.markdown(f"- {item}")
            if report.ai_explanation:
                st.caption(report.ai_explanation)

    if report.ai_optimized_code and report.ai_optimized_code.strip() != st.session_state.code.strip():
        st.markdown('<div class="cm-section-title">AI-optimised version (unverified)</div>', unsafe_allow_html=True)
        st.markdown(render_side_by_side_html(compare_code(st.session_state.code, report.ai_optimized_code)),
                    unsafe_allow_html=True)
        st.download_button("Download optimised .py", report.ai_optimized_code, file_name="optimized_code.py",
                           mime="text/x-python", icon=":material/download:")
